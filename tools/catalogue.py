#!/usr/bin/env python3
"""Write CATALOGUE_imperial.md and CATALOGUE_metric.md from the tables the parts are made from.

    python3 tools/catalogue.py           # rewrite both files
    python3 tools/catalogue.py --check   # exit 1 if either is out of date

Every size of every family, as a table, is more than a package's 'docs' can
hold (PartCAD caps 'docs.intro' at 5000 characters, rendered), so the READMEs
summarise the families and link here. The tables are rendered from
'imperial.j2' and 'metric.j2' - the very data 'imperial.yaml' and
'metric.yaml' generate the parts from - with the same template engine PartCAD
renders them with, so a catalogue that disagrees with the parts is one that was
not regenerated. Needs Jinja2, which every PartCAD installation has.
"""

import pathlib
import sys

import jinja2

ROOT = pathlib.Path(__file__).resolve().parent.parent

HEADER = """<!-- Generated by tools/catalogue.py from {source}. Do not edit: edit {source} and run it again. -->
"""


def render():
    # The package's folder, for the tables, and this one, for the templates.
    loader = jinja2.FileSystemLoader([str(ROOT), str(ROOT / "tools")])
    env = jinja2.Environment(loader=loader, keep_trailing_newline=True)
    # What PartCAD defines for every template it renders, and the tables use.
    env.globals.update({"INCH": 25.4, "INCHES": 25.4})
    return {
        "CATALOGUE_%s.md" % system: HEADER.format(source="%s.j2" % system)
        + env.get_template("catalogue_%s.md.j2" % system).render()
        for system in ("imperial", "metric")
    }


def main(argv):
    check = "--check" in argv
    stale = []
    for name, text in render().items():
        text = text.rstrip() + "\n"
        path = ROOT / name
        if path.exists() and path.read_text() == text:
            continue
        if check:
            stale.append(name)
        else:
            path.write_text(text)
            print("wrote", name)
    if stale:
        print("out of date, run tools/catalogue.py:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
